static int erl_valid(const ErlCareer *e,const SpaceRace *r,int system,int variants){
 int prizes=0;for(unsigned mask=e->prize_mask;mask;mask>>=1)prizes+=mask&1;
 if((e->fleet_n&&e->fleet_n!=prizes+1)||(!e->fleet_n&&prizes))return 0;
 if(e->fleet_n<0||e->fleet_n>ERL_FLEET||e->active_ship<0||e->active_ship>=(e->fleet_n?e->fleet_n:1)||e->licence<0||e->licence>4||e->xp<0||e->xp>10000000||e->paid>e->serial||e->referral<0||e->referral>1||e->ref_system< -1||e->ref_system>255||e->ref_hub<0||e->ref_hub>=HUB_COUNT||e->division<0||e->division>=4||e->round<0||e->round>4||e->event_kind<0||e->event_kind>ERL_TRIAL||e->event_type<0||e->event_type>ERL_TARGET||e->event_layout<0||e->event_layout>3||e->event_system<0||e->event_system>255||e->event_hub<0||e->event_hub>=HUB_COUNT||e->result<0||e->result>3||(e->prize_mask&~15u)||(e->module_pending&~15u))return 0;
 for(int i=0;i<e->fleet_n;i++){const ErlShip *s=&e->fleet[i];if(!s->id||s->id>=e->ship_id||s->hull<0||s->hull>=player_ship_count||s->health<0||s->health>100||s->shield<0||s->shield>400||s->fuel<0||s->fuel>255||s->heat<0||s->heat>100||s->weapon>=48||s->missiles<0||s->missiles>4)return 0;
  uint8_t seen[EQUIPMENT_COUNT]={0};for(int k=0;k<48;k++){int v=s->fit[k];if(v==FIT_EMPTY)continue;if(!fit_value_valid(k,v)||k/6>=fit_capacity(s->hull,k%6)||(seen[v]&&!variants))return 0;seen[v]=1;}for(int j=0;j<i;j++)if(e->fleet[j].id==s->id)return 0;
 }
 for(int i=0;i<7;i++)if(e->points[i]<0||e->points[i]>40||e->round_wins[i]<0||e->round_wins[i]>4)return 0;
 if(e->championship<0||e->championship>1||e->real_hull<0||e->real_hull>100||e->real_shield<0||e->real_shield>400||e->real_fuel<0||e->real_fuel>255||e->real_heat<0||e->real_heat>100||e->result_place<0||e->result_place>15||e->result_units<0||e->result_xp<0)return 0;
 if(e->event_kind||r->phase==RACE_COUNTDOWN||r->phase==RACE_RUNNING){if((e->event_kind&&(!e->fleet_n||r->system!=e->event_system))||(r->phase!=RACE_GRID&&r->system!=system)||r->phase<RACE_GRID||r->phase>RACE_WON||r->gate<0||r->gate>RACE_GATES||r->rivals<0||r->rivals>RACE_RIVALS||r->reserve<0||r->reserve>100||r->elapsed<0||r->elapsed>901||r->off_course<0||r->off_course>31||r->crash_id< -1||r->crash_id>=RACE_RIVALS||r->top_speed<1000||r->top_speed>25000||r->repair<0||r->repair>3.1f)return 0;
  for(int i=0;i<RACE_GATES;i++)if(r->gates[i].radius<100||r->gates[i].radius>5000||fabsf(length(r->gates[i].normal)-1)>.01f)return 0;
  for(int i=0;i<r->rivals;i++){const RaceRival *p=&r->pilot[i];if(p->gate<0||p->gate>RACE_GATES||p->mesh<0||p->mesh>=mesh_count||p->reserve<0||p->reserve>100||p->score<0||p->score>10000)return 0;}
 }
 return 1;
}
static int erl_write(FILE *f,Game *g){ErlCareer *e=&g->erl;if(e->fleet_n&&!e->event_kind)erl_ship_capture(g,e->fleet[e->active_ship].paint);e->resume_pos=g->pos;e->resume_yaw=g->yaw;e->resume_pitch=g->pitch;e->resume_roll=g->roll;e->resume_speed=g->speed;e->resume_rng=g->rng;return erl_stream(f,e,&g->race,0);}
