"""Trace the two authored female rigs at their actual 64px runtime size.

Inclusive anatomical spans are deliberately independent of RGB thresholds.
The existing ten rigs, legacy atlas, hair masks and save data are untouched.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
values = [int(v, 16) for v in re.findall(r'0x([0-9a-fA-F]{4})', (root/'src/portrait-atlas.h').read_text())]

def spans(*segments):
    rows = [0]*64
    for ya, yb, xa, xb in segments:
        for y in range(ya, yb+1):
            rows[y] |= sum(1 << x for x in range(xa, xb+1))
    return rows

human_hair = spans((0,10,0,63))
left = [32,32,31,30,30,29,28,27,26,25,24,24,23,21,20,17,17,17]
right = [35,35,35,36,37,38,39,40,40,41,41,41,42,42,42,42,42,42]
for y, (a,b) in enumerate(zip(left,right), 11):
    human_hair[y] = spans((y,y,0,a),(y,y,b,63))[y]
for y in range(29,46):
    human_hair[y] = spans((y,y,0,17 if y < 42 else 20),(y,y,51 if y < 40 else 44,63))[y]
for y in range(46,55):
    human_hair[y] = spans((y,y,0,23 if y<49 else 26),(y,y,44,63))[y]
android_hair = spans((0,10,0,63))
for y,a,b in [(11,26,45),(12,26,45),(13,25,46),(14,24,46),(15,23,46),(16,22,47),(17,21,48),(18,20,48),(19,19,49),(20,18,50),(21,17,51),(22,16,52),(23,16,54),(24,15,55),(25,14,56),(26,14,57),(27,13,57),(28,12,57),(29,12,57),(30,12,56),(31,12,56),(32,12,55),(33,12,55),(34,12,54),(35,12,54),(36,12,53),(37,12,52),(38,12,51),(39,12,50),(40,12,49),(41,12,48)]:
    android_hair[y] = spans((y,y,0,a),(y,y,b,63))[y]
head = [spans((0,47,0,63),(48,50,24,42),(51,54,32,42),(55,55,34,41)),
        spans((0,44,0,63),(45,46,23,44),(47,49,24,43),(50,51,28,43),(52,53,30,43))]
eyes = [spans((27,28,29,35),(28,29,33,36)), spans((27,28,28,34),(28,29,30,34))]
lips = [spans((40,41,24,28),(42,43,24,29),(44,44,25,28)), spans((38,39,21,26),(40,40,21,25),(41,41,22,25))]
text = ['/* Generated by tools/bake-portrait-expansion.py: authored female anatomy. */',
        'static const uint64_t portrait_female_rows[2][5][64]={']
for rig, tile in enumerate((1,77)):
    hair = (human_hair, android_hair)[rig]
    layers = [[0]*64 for _ in range(5)]
    for y in range(64):
        for x in range(64):
            if not values[tile*4096+y*64+x] & 32768:
                continue
            bit = 1 << x
            layer = 0 if head[rig][y] & bit else 2
            if hair[y] & bit: layer = 1
            if eyes[rig][y] & bit: layer = 3
            if lips[rig][y] & bit: layer = 4
            layers[layer][y] |= bit
    text.append(' {')
    for rows in layers:
        text.append('  {')
        text.extend('   '+','.join(f'0x{v:016x}ULL' for v in rows[i:i+4])+',' for i in range(0,64,4))
        text.append('  },')
    text.append(' },')
text += ['};','']
(root/'src/portrait-female-masks.h').write_text('\n'.join(text), encoding='ascii')
print('Two female rigs; traced scalp, face, neck, collar, iris and lips.')
