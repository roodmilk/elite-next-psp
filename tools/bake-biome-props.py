"""Palette-bake generated alpha props to embedded PSP cells."""
from pathlib import Path
from PIL import Image
from biome_prop_frames import load_props
root = Path(__file__).resolve().parents[1]
cells = load_props(root)
sheet = Image.new('RGBA',(192,384))
for i,cell in enumerate(cells):
    sheet.paste(cell,(i%4*48,i//4*64))
opaque = Image.new('RGB',sheet.size,(45,48,50))
opaque.paste(sheet,mask=sheet.getchannel('A'))
indexed = opaque.quantize(colors=128,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
palette = indexed.getpalette()[:384]
lines = ['/* Generated by tools/bake-biome-props.py. */','static const unsigned biome_prop_palette[128]={']
lines += [f'RGB({palette[i]},{palette[i+1]},{palette[i+2]}),' for i in range(0,384,3)]
lines += ['};','static const unsigned char biome_prop_pixels[24][3072]={']
for i in range(24):
    lines.append('{')
    for y in range(64):
        lines.append(','.join(str(indexed.getpixel((i%4*48+x,i//4*64+y))) if cells[i].getpixel((x,y))[3]>160 else '255' for x in range(48))+',')
    lines.append('},')
lines.append('};')
(root/'src/generated/biome-props-pixels.h').write_text('\n'.join(lines)+'\n')
dest=root/'assets/generated/biome-props'
dest.mkdir(parents=True,exist_ok=True)
preview = indexed.convert('RGBA')
preview.putalpha(sheet.getchannel('A'))
preview.save(dest/'kit.png')
print('24 transparent cells; 73728 indexed bytes')
