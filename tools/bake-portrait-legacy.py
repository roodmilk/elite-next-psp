"""Extract complete legacy faces from reviewed, nonuniform source-sheet rows.

The old equal-height grid included shoulders from the preceding row. These
explicit gutters belong to the authored sheets, not to a runtime colour test.
Keep the original rig atlas unchanged: modular anatomy is aligned to that grid.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SHEETS = (
    ('pulp-humans-16.png', (0,292,551,809,1086)),
    ('pulp-orrith-amphibian-16.png', (0,326,615,849,1086)),
    ('pulp-insect-sauran-16.png', (0,310,571,813,1086)),
    ('pulp-avian-masked-16.png', (0,323,592,843,1086)),
    ('pulp-robots-12.png', (0,375,725,1086)),
    ('pulp-androids-12.png', (0,369,727,1086)),
    ('pulp-crystal-fungal-8.png', (0,451,887)),
)

def rgba1555(p):
    r,g,b,a = p
    return 0 if a < 64 else 0x8000|((r>>3)<<10)|((g>>3)<<5)|(b>>3)

tiles = []
out = ROOT/'outputs/profile379-audit'
out.mkdir(parents=True,exist_ok=True)
for name, gutters in SHEETS:
    sheet = Image.open(ROOT/'assets/source/portraits'/name).convert('RGBA')
    assert sheet.height == gutters[-1]
    for row in range(len(gutters)-1):
        for col in range(4):
            face = sheet.crop((col*sheet.width//4,gutters[row],(col+1)*sheet.width//4,gutters[row+1]))
            # A two-pixel native gutter contains the whole source cell and
            # prevents the frame or subsequent tile from touching the face.
            tile = Image.new('RGBA',(64,64))
            tile.paste(face.resize((60,60),Image.Resampling.NEAREST),(2,2))
            tiles.append([rgba1555(p) for p in tile.getdata()])
assert len(tiles) == 96
packed=[];offsets=[]
for tile in tiles:
    offsets.append(len(packed))
    for y in range(64):
        row=tile[y*64:y*64+64];used=[x for x,p in enumerate(row) if p&32768]
        start=used[0] if used else 0;count=used[-1]-start+1 if used else 0
        packed.extend((start,count));packed.extend(row[start:start+count])
offsets.append(len(packed))
lines=['/* Generated by tools/bake-portrait-legacy.py; lossless row spans. */',
       'static const uint32_t portrait_legacy_offsets[97]={'+','.join(map(str,offsets))+'};',
       'static const uint16_t portrait_legacy_data[]={']
lines.extend(' '+','.join(f'0x{p:04X}' for p in packed[i:i+16])+',' for i in range(0,len(packed),16))
lines += ['};', '''static const uint16_t *portrait_legacy_source(int base){
 static uint16_t tile[4096];static int previous=-1;
 if(previous!=base){
  memset(tile,0,sizeof(tile));const uint16_t *row=portrait_legacy_data+portrait_legacy_offsets[base];
  for(int y=0;y<64;y++){int start=*row++,count=*row++;memcpy(tile+y*64+start,row,count*sizeof(uint16_t));row+=count;}
  previous=base;
 }return tile;
}''','']
(ROOT/'src/portrait-legacy-atlas.h').write_text('\n'.join(lines),encoding='ascii')
# Only twelve source tiles feed modular rigs. Preserve those exact old pixels
# and alignment, without shipping the other 84 superseded contaminated tiles.
import re
old=[int(v,16) for v in re.findall(r'0x([0-9A-Fa-f]{4})',(ROOT/'src/portrait-atlas.h').read_text())]
rigs=(0,16,24,32,40,48,64,76,56,88,1,77)
rig_lines=['/* Generated by tools/bake-portrait-legacy.py; original rig pixels. */',
           'enum {PORTRAIT_PULP_TILE=64};',
           'static const uint16_t portrait_rig_bases[12][4096]={']
for base in rigs:
    rig_lines.append(' {')
    rig_lines.extend('  '+','.join(f'0x{p:04X}' for p in old[base*4096+i:base*4096+i+16])+',' for i in range(0,4096,16))
    rig_lines.append(' },')
rig_lines+=['};','static const uint16_t *portrait_rig_source(int species,int female){return portrait_rig_bases[female?(species==7?11:10):species];}','']
(ROOT/'src/portrait-rig-atlas.h').write_text('\n'.join(rig_lines),encoding='ascii')
for page in range(4):
    im=Image.new('RGB',(480,272),(15,24,34))
    for n in range(24):
        face=Image.new('RGB',(64,64))
        face.putdata([(((p>>10)&31)*255//31,((p>>5)&31)*255//31,(p&31)*255//31) if p&32768 else (15,24,34) for p in tiles[page*24+n]])
        im.paste(face.resize((56,56),Image.Resampling.NEAREST),((n%8)*60,(n//8)*88+14))
    im.save(out/f'clean-atlas-{page}.png')
print(f'96 isolated faces; {len(packed)*2+388+8192+98304:,} bytes including legacy cache and twelve original rigs, versus 786,432 bytes originally.')
