"""Compile authored newspaper compositions; never regenerate the draft corpus.

Text, art and furniture remain separate bounded runtime primitives. This tool
validates each complete text block before emitting native font lines.
"""
from pathlib import Path
from PIL import Image
import hashlib, json, textwrap

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'content/newspapers/approved-issues.json'
ASSETS = {'arrival': 'arrival-168x112.png', 'seed': 'seed-150x100.png',
          'pirates': 'pirates-180x90.png', 'tools': 'tools-150x100.png'}

def colour(s):
    return int('ff'+s[4:6]+s[2:4]+s[:2], 16)

def overlap(a,b):
    return a[0]<b[0]+b[2] and a[0]+a[2]>b[0] and a[1]<b[1]+b[3] and a[1]+a[3]>b[1]

def expanded(page):
    result=[]
    for op in page['ops']:
        if op['kind']=='paragraph':
            lines=textwrap.wrap(op['text'].upper(),op['cols'],break_long_words=False,break_on_hyphens=False)
            assert op['y']+(len(lines)-1)*9+8 <= op['bottom'], (page['recipe'],op['text'],len(lines))
            for i,s in enumerate(lines):
                result.append(dict(kind='text',x=op['x'],y=op['y']+i*9,text=s,scale=1,ink=op['ink']))
        else: result.append(op.copy())
    return result

def contrast(a,b):
    def lum(c):
        vals=[int(c[i:i+2],16)/255 for i in (0,2,4)]
        vals=[v/12.92 if v<=.04045 else ((v+.055)/1.055)**2.4 for v in vals]
        return sum(v*w for v,w in zip(vals,(.2126,.7152,.0722)))
    x,y=sorted((lum(a),lum(b)))
    return (y+.05)/(x+.05)

def main():
    data=json.loads(SOURCE.read_text()); collection=json.loads((SOURCE.parent/'collection.json').read_text())
    header=['/* Authored print compositions. Generated by compile-newspaper-compositions.py. */',
        'typedef struct {short x,y,w,h;unsigned ink;unsigned short kind,arg;const char *text;} NewspaperPrintOp;',
        'typedef struct {unsigned short system,page,first,count,puzzle;const char *recipe;} NewspaperComposition;',
        'typedef struct {unsigned short system,mark;unsigned palette[6];const char *masthead,*motto;} NewspaperPrintIdentity;']
    # Native source illustrations only. RGB565 avoids decoding or allocation at runtime.
    for name,file in ASSETS.items():
        im=Image.open(ROOT/'assets/source/newspaper-approved'/file).convert('RGB')
        pixels=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in im.getdata()]
        header.append('static const unsigned short news_print_art_'+name+'[]={'+','.join(hex(p) for p in pixels)+'};')
    header.append('typedef struct {unsigned short w,h;const unsigned short *pixels;} NewspaperPrintArt;')
    header.append('static const NewspaperPrintArt newspaper_print_art[]={'+','.join('{%d,%d,news_print_art_%s}'%(*Image.open(ROOT/'assets/source/newspaper-approved'/f).size,n) for n,f in ASSETS.items())+'};')
    # Exact authored 16px marks from the approved code references, not a seeded logo.
    marks=json.loads((SOURCE.parent/'print-marks.json').read_text())
    names=['lantern','leaf','orbit','wake','ledger']
    header.append('static const char *const newspaper_print_marks[5][16]={'+','.join('{'+','.join(json.dumps(row) for row in marks[n])+'}' for n in names)+'};')
    identities=[];pages=[];ops=[];audit=[]
    kinds={'box':0,'text':1,'art':2,'puzzle':3,'spot':4}
    for issue in data['issues']:
        sys=issue['system'];assert collection[sys]['name']==issue['name']
        identities.append('{%d,%d,{%s},%s,%s}'%(sys,names.index(issue['mark']),','.join(hex(colour(c))+'u' for c in issue['palette']),json.dumps(issue['masthead']),json.dumps(issue['motto'])))
        assert len(issue['masthead'])*16+56<=380 and len(issue['motto'])*8+57<=380
        for page in issue['pages']:
            assert 0<=page['page']<collection[sys]['identity']['page_count']
            first=len(ops);text_rects=[];art_rects=[];contrasts=[];native=expanded(page)
            for op in native:
                kind=op['kind'];x=op['x'];y=op['y'];w=op.get('w',0);h=op.get('h',0);arg=0;s=''
                if kind=='text':
                    s=op['text'];arg=op.get('scale',1);assert arg in (1,2)
                    assert all(32<=ord(c)<=126 for c in s),s
                    w=len(s)*8*arg;h=8*arg;text_rects.append((x,y,w,h,s))
                if kind=='text':
                    bg=issue['palette'][0]
                    for earlier in native[:native.index(op)]:
                        if earlier['kind']=='box' and earlier['x']<=x and earlier['y']<=y and earlier['x']+earlier['w']>=x+w and earlier['y']+earlier['h']>=y+h:bg=earlier['ink']
                    ink=op.get('ink',issue['palette'][1]);ratio=contrast(ink,bg)
                    assert ratio>=3.0,(issue['name'],page['page'],s,ratio)
                    contrasts.append(ratio)
                    if ink==issue['palette'][1] and bg==issue['palette'][0]:assert ratio>=4.5
                if kind=='art':
                    arg=list(ASSETS).index(op['asset']);assert (w,h)==Image.open(ROOT/'assets/source/newspaper-approved'/ASSETS[op['asset']]).size
                    art_rects.append((x,y,w,h,op['asset']))
                assert 0<=x and 84<=y and x+w<=480 and y+h<=248,(issue['name'],page['page'],op)
                ops.append('{%d,%d,%d,%d,%su,%d,%d,%s}'%(x,y,w,h,hex(colour(op.get('ink',issue['palette'][1]))),kinds[kind],arg,json.dumps(s)))
            for i,t in enumerate(text_rects):
                for other in text_rects[:i]+art_rects:assert not overlap(t,other),(issue['name'],page['page'],t,other)
            puzzle=collection[sys]['pages'][page['page']].get('puzzle',0) if any(op['kind']=='puzzle' for op in page['ops']) else 0
            pages.append('{%d,%d,%d,%d,%d,%s}'%(sys,page['page'],first,len(ops)-first,puzzle,json.dumps(page['recipe'])))
            audit.append(dict(system=sys,page=page['page'],recipe=page['recipe'],text_rectangles=text_rects,art_rectangles=art_rects,source_sha256=hashlib.sha256(json.dumps({k:v for k,v in page.items() if k not in ('authored','edited','proofread')},sort_keys=True).encode()).hexdigest(),automated_bounds=True,automated_overlap=True,font_safe=True,contrast_minimum=min(contrasts),contrast_pass=True,duplication_pass=True))
    # A complete repeated sentence is an editorial error, not a layout success.
    duplicates=[];seen={}
    for issue in data['issues']:
        for page in issue['pages']:
            for op in page['ops']:
                if op['kind']=='paragraph' and len(op['text'])>80:
                    norm=op['text'].upper().strip()
                    if norm in seen:duplicates.append([seen[norm],[issue['name'],page['page']]])
                    seen[norm]=[issue['name'],page['page']]
    assert not duplicates,duplicates
    header+=['static const NewspaperPrintIdentity newspaper_print_identity[]={'+',\n'.join(identities)+'};',
             'static const NewspaperPrintOp newspaper_print_ops[]={'+',\n'.join(ops)+'};',
             'static const NewspaperComposition newspaper_compositions[]={'+',\n'.join(pages)+'};']
    (ROOT/'src/newspaper-composition-data.h').write_text('\n'.join(header)+'\n')
    (SOURCE.parent/'composition-audit.json').write_text(json.dumps(audit,indent=2)+'\n')
    print(f'{len(pages)} authored native compositions; {len(ops)} primitives; bounds, overlap and font checks pass. Runtime inspection remains separate.')

if __name__=='__main__': main()
